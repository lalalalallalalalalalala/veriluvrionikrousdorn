//! Кириллица 8×8. Младший бит — левый пиксель, как у font8x8.

pub fn bits(ch: char) -> Option<[u8; 8]> {
    let index = match ch {
        'а'..='я' => ch as usize - 'а' as usize,
        'А'..='Я' => ch as usize - 'А' as usize,
        'ё' | 'Ё' => 32,
        _ => return None,
    };
    GLYPH.get(index).copied()
}

